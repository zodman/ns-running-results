export function evaluateRegions(races, passport) {
  const list = NS_REGIONS.map((reg) => {
    const catalogInReg = passport.entries.filter((e) => e.region === reg.id);
    const caughtCatalog = catalogInReg.filter((e) => e.caught);
    const matchedRaces = races.filter(
      (r) =>
        reg.locMatch.test(r.raceLocation || "") ||
        catalogInReg.some((c) => c.match.test(`${r.name} ${r.subEvent || ""}`))
    );
    const raceCount = matchedRaces.length;
    const unlocked = raceCount > 0;
    const mastered = raceCount >= reg.masteryAt;
    return {
      ...reg,
      raceCount,
      caughtMedals: caughtCatalog.length,
      totalMedals: catalogInReg.length,
      unlocked,
      mastered
    };
  });

  const unlockedCount = list.filter((r) => r.unlocked).length;
  return {
    regions: list,
    unlockedCount,
    totalRegions: list.length,
    percent: Math.round((unlockedCount / list.length) * 100)
  };
}

export function evaluateTrophies(races, passport, regionStats) {
  // Accurately identify a 42.2K full marathon
  // (Never check race title/name because festivals like 'Medavie Blue Nose Marathon' host 5K/10K/Half races)
  const isFullMarathon = (r) => {
    if (!r) return false;
    const km = Number(r.km) || 0;
    // Shorter distance or explicitly non-marathon category cannot be full marathon
    if (km > 0 && km < 40) return false;
    if (["5K", "10K", "Half Marathon", "Half"].includes(r.category)) return false;

    // 1. Distance check (~42.2K)
    if (km >= 41.5 && km <= 43.5) return true;

    // 2. Category check
    if (r.category === "Marathon") return true;

    // 3. SubEvent check
    const sub = String(r.subEvent || "").toLowerCase();
    if (/full[\s-]*marathon|42\.2\s*k|\b42k\b/i.test(sub)) return true;
    if (/\bmarathon\b/i.test(sub) && !/half/i.test(sub)) return true;

    return false;
  };

  // Accurately identify a 21.1K half marathon
  const isHalfMarathon = (r) => {
    if (!r) return false;
    const km = Number(r.km) || 0;
    if (km > 0 && (km < 20 || km > 23)) return false;
    if (["5K", "10K", "Marathon"].includes(r.category)) return false;

    // 1. Distance check (~21.1K)
    if (km >= 20.5 && km <= 22.5) return true;

    // 2. Category check
    if (r.category === "Half Marathon" || r.category === "Half") return true;

    // 3. SubEvent check
    const sub = String(r.subEvent || "").toLowerCase();
    if (/half[\s-]*marathon|21\.1\s*k|\b21k\b|\bhalf\b/i.test(sub)) return true;

    return false;
  };

  // 1. Distance Grand Slam
  const standardDists = ["5K", "10K", "Half Marathon", "Marathon"];
  const grandSlamRaces = standardDists
    .map((d) => {
      const matching = races.filter((r) => {
        if (d === "Marathon") return isFullMarathon(r);
        if (d === "Half Marathon") return isHalfMarathon(r);
        if (d === "10K") return r.category === "10K" || (r.km >= 9.8 && r.km <= 10.5);
        if (d === "5K") return r.category === "5K" || (r.km >= 4.8 && r.km <= 5.5);
        return r.category === d;
      });
      if (!matching.length) return null;
      const timed = matching.filter((r) => r.officialSec);
      return timed.length
        ? timed.reduce((a, b) => (a.officialSec < b.officialSec ? a : b))
        : matching[0];
    })
    .filter(Boolean);
  const doneDists = grandSlamRaces.map((r) => {
    if (isFullMarathon(r)) return "Marathon";
    if (isHalfMarathon(r)) return "Half Marathon";
    return r.category;
  });

  // 2. 5K Club
  const fiveKRaces = races
    .filter((r) => r.category === "5K")
    .sort((a, b) => (b.timestamp || 0) - (a.timestamp || 0));
  const fiveKCount = fiveKRaces.length;

  // 2b. First Half Marathon Finisher (21.1K)
  const halfRaces = races
    .filter(isHalfMarathon)
    .sort((a, b) => (a.timestamp || 0) - (b.timestamp || 0)); // Earliest first
  const firstHalf = halfRaces[0] || null;

  // 2c. First Full Marathon Finisher (42.2K)
  const marathonRaces = races
    .filter(isFullMarathon)
    .sort((a, b) => (a.timestamp || 0) - (b.timestamp || 0)); // Earliest first
  const firstMarathon = marathonRaces[0] || null;

  // 2d. 10K Milestone Finisher
  const tenKRaces = races
    .filter((r) => r.category === "10K" || (r.km >= 9.8 && r.km <= 10.5))
    .sort((a, b) => (a.timestamp || 0) - (b.timestamp || 0));
  const firstTenK = tenKRaces[0] || null;

  // 2e. Cumulative race kilometers (Century Club)
  const totalKm = races.reduce((sum, r) => sum + (Number(r.km) || 0), 0);
  const racesWithKm = races.filter((r) => Number(r.km) > 0);

  // 3. Bridge Runner
  const bridgeRaces = races
    .filter((r) => /harbour hustle|macpass miles/i.test(r.name))
    .sort((a, b) => (b.timestamp || 0) - (a.timestamp || 0));
  const bridgeRace = bridgeRaces[0] || null;

  // 4. Island Hopper
  const islandRaces = races
    .filter((r) =>
      /mcnab|louisbourg|mabou|mhàbu|escaouette|cape breton|sydney/i.test(
        `${r.name} ${r.raceLocation || ""}`
      )
    )
    .sort((a, b) => (b.timestamp || 0) - (a.timestamp || 0));
  const islandRace = islandRaces[0] || null;

  // 5. Back-to-Back Warrior (2 races within 14 days)
  const dated = races
    .filter((r) => r.timestamp > 0)
    .sort((a, b) => a.timestamp - b.timestamp);
  let backToBackPair = null;
  for (let i = 1; i < dated.length; i++) {
    const diffDays = Math.round((dated[i].timestamp - dated[i - 1].timestamp) / (1000 * 60 * 60 * 24));
    if (diffDays >= 1 && diffDays <= 14) {
      backToBackPair = {
        a: dated[i - 1].name,
        b: dated[i].name,
        days: diffDays,
        races: [dated[i - 1], dated[i]]
      };
      break;
    }
  }

  // 6. All-Seasons Runner
  const seasonLabels = ["Winter", "Spring", "Summer", "Fall"];
  const seasonRaceMap = {};
  for (const r of races) {
    const d = new Date(r.iso);
    if (Number.isNaN(d.getTime())) continue;
    const m = d.getMonth() + 1;
    const season = m <= 3 ? "Winter" : m <= 6 ? "Spring" : m <= 9 ? "Summer" : "Fall";
    if (!seasonRaceMap[season]) seasonRaceMap[season] = r;
  }
  const seasonsHit = new Set(Object.keys(seasonRaceMap));
  const missingSeasons = seasonLabels.filter((s) => !seasonsHit.has(s));
  const seasonRacesList = seasonLabels.map((s) => seasonRaceMap[s]).filter(Boolean);

  // 7. Course PR Crusher (beat previous year's time on same catalog race & same distance)
  let coursePR = null;
  for (const item of passport.entries) {
    if (item.count < 2) continue;
    const runs = races
      .filter((r) => item.match.test(`${r.name} ${r.subEvent || ""}`) && r.officialSec && r.timestamp)
      .sort((a, b) => a.timestamp - b.timestamp);
    // Group by distance/category so Half -> 5K doesn't false-trigger
    const byCat = {};
    for (const r of runs) {
      const key = r.category || "Other";
      if (!byCat[key]) byCat[key] = [];
      byCat[key].push(r);
    }
    for (const catRuns of Object.values(byCat)) {
      for (let i = 1; i < catRuns.length; i++) {
        if (catRuns[i].officialSec < catRuns[i - 1].officialSec) {
          const diff = catRuns[i - 1].officialSec - catRuns[i].officialSec;
          coursePR = {
            name: item.name,
            saved: `${Math.floor(diff / 60)}m ${diff % 60}s faster`,
            races: [catRuns[i - 1], catRuns[i]]
          };
          break;
        }
      }
      if (coursePR) break;
    }
    if (coursePR) break;
  }

  // 8. NS Road Tripper (5+ unique towns)
  const townRaceMap = {};
  for (const r of races) {
    const loc = r.shortLocation;
    if (loc && loc !== "Nova Scotia" && !townRaceMap[loc]) {
      townRaceMap[loc] = r;
    }
  }
  const uniqueTowns = new Set(Object.keys(townRaceMap));
  const townRacesList = Object.values(townRaceMap);

  // 9. Multi-Year Loyalist (same annual race 3+ times)
  const loyalistRace = passport.entries.find((e) => e.count >= 3);
  const loyalistRaces = loyalistRace
    ? races
        .filter((r) => loyalistRace.match.test(`${r.name} ${r.subEvent || ""}`))
        .sort((a, b) => (b.timestamp || 0) - (a.timestamp || 0))
    : [];

  // 10 & 11. Region Explorer / Conqueror representative races
  const regionSampleRaces = regionStats.regions
    .filter((reg) => reg.unlocked)
    .map((reg) => {
      const catInReg = passport.entries.filter((e) => e.region === reg.id);
      return races.find(
        (r) =>
          reg.locMatch.test(r.raceLocation || "") ||
          catInReg.some((c) => c.match.test(`${r.name} ${r.subEvent || ""}`))
      );
    })
    .filter(Boolean);

  const trophies = [
    {
      id: "first-marathon",
      icon: "🏅",
      title: "First Marathon",
      desc: "Conquer the iconic 42.2K distance in an official Nova Scotia marathon",
      unlocked: Boolean(firstMarathon),
      progress: firstMarathon
        ? `Completed at ${firstMarathon.name} (${firstMarathon.officialTime})`
        : "Finish a 42.2K Marathon in NS",
      races: marathonRaces
    },
    {
      id: "first-half",
      icon: "🏃",
      title: "First Half Marathon",
      desc: "Conquer 21.1K in an official Nova Scotia half marathon",
      unlocked: Boolean(firstHalf),
      progress: firstHalf
        ? `Completed at ${firstHalf.name} (${firstHalf.officialTime})`
        : "Finish a 21.1K Half Marathon in NS",
      races: halfRaces
    },
    {
      id: "first-10k",
      icon: "🎯",
      title: "10K Milestone",
      desc: "Complete an official 10K road race in Nova Scotia",
      unlocked: Boolean(firstTenK),
      progress: firstTenK
        ? `Completed at ${firstTenK.name} (${firstTenK.officialTime})`
        : "Finish a 10K Race in NS",
      races: tenKRaces
    },
    {
      id: "grand-slam",
      icon: "🏆",
      title: "Distance Grand Slam",
      desc: "Finish a 5K, 10K, Half Marathon & Marathon",
      unlocked: doneDists.length === 4,
      progress: `${doneDists.length} / 4 distances (${doneDists.join(", ") || "none yet"})`,
      races: grandSlamRaces
    },
    {
      id: "100k-club",
      icon: "💯",
      title: "Century Club (100K)",
      desc: "Accumulate 100+ official racing kilometers across Nova Scotia",
      unlocked: totalKm >= 100,
      progress:
        totalKm >= 100
          ? `${Math.round(totalKm)} km total raced across NS`
          : `${totalKm.toFixed(1)} / 100 km completed`,
      races: racesWithKm
    },
    {
      id: "5k-club",
      icon: "⚡",
      title: "5K Club",
      desc: "Complete 3 or more official 5K races",
      unlocked: fiveKCount >= 3,
      progress: fiveKCount >= 3 ? `${fiveKCount}× 5K finishes` : `${fiveKCount} / 3 5K races`,
      races: fiveKRaces
    },
    {
      id: "bridge-runner",
      icon: "🌉",
      title: "Bridge Runner",
      desc: "Run across the Macdonald Bridge at Harbour Hustle",
      unlocked: Boolean(bridgeRace),
      progress: bridgeRace ? `Completed (${bridgeRace.officialTime})` : "Run Harbour Hustle (Aug)",
      races: bridgeRaces
    },
    {
      id: "island-hopper",
      icon: "🏝️",
      title: "Island Hopper",
      desc: "Finish McNabs Half Marathon or any Cape Breton race",
      unlocked: Boolean(islandRace),
      progress: islandRace ? islandRace.name : "Run McNabs or Cape Breton",
      races: islandRaces
    },
    {
      id: "back-to-back",
      icon: "🔥",
      title: "Back-to-Back Warrior",
      desc: "Finish two official races within 14 days",
      unlocked: Boolean(backToBackPair),
      progress: backToBackPair
        ? `${backToBackPair.days} days apart`
        : "Race twice within 2 weeks",
      races: backToBackPair ? backToBackPair.races : []
    },
    {
      id: "all-seasons",
      icon: "🗓️",
      title: "All-Seasons Runner",
      desc: "Race in Winter, Spring, Summer, and Fall",
      unlocked: seasonsHit.size === 4,
      progress:
        seasonsHit.size === 4
          ? "All 4 seasons unlocked"
          : `Missing: ${missingSeasons.join(", ")}`,
      races: seasonRacesList
    },
    {
      id: "course-pr",
      icon: "📈",
      title: "Course PR Crusher",
      desc: "Beat your own previous time on the exact same race & distance",
      unlocked: Boolean(coursePR),
      progress: coursePR ? `${coursePR.name} (${coursePR.saved})` : "Return & beat a course PB",
      races: coursePR ? coursePR.races : []
    },
    {
      id: "road-tripper",
      icon: "🚗",
      title: "NS Road Tripper",
      desc: "Race in 5+ different Nova Scotia towns",
      unlocked: uniqueTowns.size >= 5,
      progress: `${uniqueTowns.size} / 5 towns raced`,
      races: townRacesList
    },
    {
      id: "loyalist",
      icon: "🥇",
      title: "Multi-Year Loyalist",
      desc: "Finish the same annual race 3+ times",
      unlocked: Boolean(loyalistRace),
      progress: loyalistRace ? `${loyalistRace.name} (×${loyalistRace.count})` : "Run an event 3+ times",
      races: loyalistRaces
    },
    {
      id: "half-province",
      icon: "🗺️",
      title: "Half-Province Explorer",
      desc: "Capture 4+ of Nova Scotia's 7 running regions",
      unlocked: regionStats.unlockedCount >= 4,
      progress: `${regionStats.unlockedCount} / 4 regions`,
      races: regionSampleRaces
    },
    {
      id: "province-conqueror",
      icon: "👑",
      title: "Province Conqueror",
      desc: "Capture all 7 Nova Scotia running regions",
      unlocked: regionStats.unlockedCount === 7,
      progress: `${regionStats.unlockedCount} / 7 regions`,
      races: regionSampleRaces
    }
  ];

  // Unlocked first, then locked
  trophies.sort((a, b) => (a.unlocked === b.unlocked ? 0 : a.unlocked ? -1 : 1));

  return {
    trophies,
    unlockedCount: trophies.filter((t) => t.unlocked).length,
    totalCount: trophies.length
  };
}
